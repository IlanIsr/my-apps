/**
 * Builds `lib/shass.ts` — the structure of the Babylonian Talmud (every
 * masekhet with Gemara: its last amud and its perakim) — from Sefaria's index
 * API. Run once, by hand; the app never calls Sefaria.
 *
 *   node scripts/build-shass.ts
 *
 * Amudim are numbered like Sefaria's sections: 1 = 1a, 2 = 1b, 3 = 2a, …
 * (see `amudLabel` in lib/study-logic.ts).
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://www.sefaria.org/api";

type TocNode = {
  category?: string;
  heCategory?: string;
  title?: string;
  contents?: TocNode[];
};

type Title = { lang: string; text: string; primary?: boolean };

type Index = {
  title: string;
  schema: { lengths: number[]; titles: Title[] };
  alt_structs: {
    Chapters: { nodes: { wholeRef: string; titles: Title[] }[] };
  };
};

const SEDARIM: Record<string, string> = {
  "Seder Zeraim": "zeraim",
  "Seder Moed": "moed",
  "Seder Nashim": "nashim",
  "Seder Nezikin": "nezikin",
  "Seder Kodashim": "kodashim",
  "Seder Tahorot": "tahorot",
};

async function get<T>(path: string): Promise<T> {
  const res = await fetch(`${API}${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return (await res.json()) as T;
}

const amud = (daf: string, side: string) =>
  (Number(daf) - 1) * 2 + (side === "a" ? 1 : 2);

/** "Berakhot 2a:1-13a:15" → [3, 25]. */
function range(ref: string): [number, number] {
  const m = /(\d+)([ab])(?::\d+)?(?:-(?:(\d+)([ab]))?)?/.exec(ref);
  if (!m) throw new Error(`Unparsed ref: ${ref}`);
  const start = amud(m[1]!, m[2]!);
  return [start, m[3] ? amud(m[3], m[4]!) : start];
}

const primary = (titles: Title[], lang: string) =>
  titles.find((t) => t.lang === lang && t.primary)?.text ?? "";

const toc = await get<TocNode[]>("/index");
const bavli = toc
  .find((n) => n.category === "Talmud")
  ?.contents?.find((n) => n.category === "Bavli");
if (!bavli?.contents) throw new Error("Bavli not found in the index");

const out = [];
for (const seder of bavli.contents) {
  const key = SEDARIM[seder.category ?? ""];
  if (!key) continue;
  for (const { title } of seder.contents ?? []) {
    if (!title) continue;
    const index = await get<Index>(
      `/v2/raw/index/${encodeURIComponent(title)}`,
    );
    const perakim = index.alt_structs.Chapters.nodes.map((node) => {
      const [start, end] = range(node.wholeRef);
      return { he: primary(node.titles, "he"), start, end };
    });
    out.push({
      key: title,
      he: primary(index.schema.titles, "he"),
      seder: key,
      first: perakim[0]!.start,
      last: index.schema.lengths[0]!,
      perakim,
    });
    console.log(title, perakim.length, "perakim");
  }
}

const file = join(dirname(fileURLToPath(import.meta.url)), "../lib/shass.ts");
writeFileSync(
  file,
  `/**
 * The Babylonian Talmud, generated by \`scripts/build-shass.ts\` from
 * Sefaria's index — do not edit by hand. Amudim are numbered 1 = 1a, 2 = 1b,
 * 3 = 2a, …; \`first\` / \`last\` = the masekhet's first and last amud, each
 * perek's \`start\` / \`end\` = the amudim it begins and ends on (two perakim
 * can share one).
 */

import type { Masekhet } from "./study-logic";

export const SHASS: readonly Masekhet[] = ${JSON.stringify(out, null, 2)};
`,
);
console.log(`Wrote ${out.length} masekhtot to ${file}`);
